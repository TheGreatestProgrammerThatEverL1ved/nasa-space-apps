import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

for (const locale of ['en', 'ua'] as const) {
  test(`guided real mission, no payout, help restoration and narrow reflow (${locale})`, async ({ page }, testInfo) => {
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('./')
    if (locale === 'ua') await page.getByRole('button', { name: 'Українська', exact: true }).click()
    await page.getByRole('button', { name: locale === 'en' ? 'Start guided mission' : 'Почати навчальну місію', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toBeVisible()
    await dialog.getByRole('button', { name: locale === 'en' ? 'Launch guided simulation' : 'Запустити навчальну симуляцію' }).click()
    await expect(page.getByTestId('guide-latency')).toContainText(/7[.,]1/)
    await expect(dialog.getByRole('heading', { level: 2 })).toBeFocused()
    await dialog.getByLabel(locale === 'en' ? 'Guided ground service' : 'Навчальний наземний сервіс').selectOption('gs-network')
    await dialog.getByRole('button', { name: locale === 'en' ? 'Run repaired design' : 'Перевірити виправлений проєкт' }).click()
    await expect(page.getByTestId('guide-latency')).toContainText(/3[.,]1/)
    expect(await page.evaluate(() => localStorage.getItem('mission-forge.campaign.v1'))).toBeNull()
    const scan = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(scan.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) }))).toEqual([])
    await page.screenshot({ path: testInfo.outputPath(`academy-pass-${locale}.png`) })
    await dialog.getByRole('button', { name: locale === 'en' ? 'Return to my design' : 'Повернутися до мого проєкту' }).click()
    const help = page.getByRole('button', { name: locale === 'en' ? 'Help / Academy' : 'Допомога / Академія', exact: true })
    await expect(page.locator('.help-entry')).toBeFocused()
    await expect(page.locator('#groundId')).toHaveValue('gs-single')
    const run = page.getByRole('button', { name: locale === 'en' ? 'Run mission' : 'Запустити місію', exact: true })
    await run.click()
    await page.locator('#groundId').selectOption('gs-network')
    await help.click()
    await dialog.getByText(locale === 'en' ? 'Commander’s field guide' : 'Довідник командира', { exact: true }).click()
    await page.setViewportSize({ width: 320, height: 844 })
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
    await dialog.getByRole('button', { name: locale === 'en' ? 'Українська' : 'English', exact: true }).click()
    await page.keyboard.press('Escape')
    await expect(page.locator('.help-entry')).toBeFocused()
    await expect(page.getByTestId('stale-notice')).toBeVisible()
    await expect(page.locator('#groundId')).toHaveValue('gs-network')
    await expect(page.getByTestId('latency-value')).toContainText(/7[.,]1/)
    await page.reload()
    await expect(page.getByRole('button', { name: 'Start guided mission', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'Help / Academy', exact: true }).click()
    await dialog.getByRole('button', { name: 'Start / replay guided mission' }).click()
    await expect(dialog.getByRole('button', { name: 'Launch guided simulation' })).toBeVisible()
    await dialog.getByRole('button', { name: 'Skip tutorial' }).click()
  })
}

test('skipping first-run guide is persistent and manual typed repairs focus actual controls', async ({ page }, testInfo) => {
  await page.goto('./')
  await page.getByRole('button', { name: 'Skip tutorial', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('night02-first-load.png') })
  await page.locator('#arrayId').selectOption('arr-deploy-m')
  await page.getByRole('button', { name: 'Run mission', exact: true }).click()
  await page.getByRole('link', { name: /Back to|Return to|Revise/i }).first().click()
  await expect(page.locator('#arrayId')).toBeFocused()
  await page.locator('#arrayId').selectOption('arr-deploy-l')
  await page.locator('#busId').selectOption('bus-6u')
  await page.getByRole('button', { name: 'Run mission', exact: true }).click()
  await page.getByRole('link', { name: /Back to|Return to|Revise/i }).first().click()
  await expect(page.locator('#busId')).toBeFocused()
  await page.locator('#busId').selectOption('bus-12u')
  await page.getByRole('button', { name: /^Solar array/ }).click()
  await expect(page.locator('#arrayId')).toBeFocused()
  await page.locator('.spacecraft-bay').screenshot({ path: testInfo.outputPath('night02-workbench.png') })
  await page.locator('#result-heading').focus()
  await page.keyboard.press('?')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('#result-heading')).toBeFocused()
})

test('guide launch inside campaign never pays or replaces the player draft/report', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('button', { name: 'Play campaign', exact: true }).click()
  await page.locator('#batteryId').selectOption('bat-m')
  await page.getByRole('button', { name: 'Start guided mission', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Launch guided simulation' }).click()
  await dialog.locator('#guide-ground').selectOption('gs-network')
  await dialog.getByRole('button', { name: 'Run repaired design' }).click()
  await dialog.getByRole('button', { name: 'Return to my design' }).click()
  await expect(page.getByTestId('campaign-credits')).toContainText(/^0 /)
  await expect(page.getByTestId('campaign-progress')).toContainText(/0.*4/)
  await expect(page.locator('#batteryId')).toHaveValue('bat-m')
  await expect(page.getByTestId('latency-value')).toHaveCount(0)
  expect(await page.evaluate(() => localStorage.getItem('mission-forge.campaign.v1'))).toBeNull()
})
