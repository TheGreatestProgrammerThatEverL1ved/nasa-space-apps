import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

for (const locale of ['en', 'ua'] as const) {
  test(`orbital upgrade tree supports mapping-first and relay-first branches (${locale})`, async ({ page }) => {
    const en = locale === 'en'
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.addInitScript(() => localStorage.setItem('mission-forge.academy.v1', 'seen'))
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto('./?renderer=svg')
    if (!en) await page.getByRole('button', { name: 'Українська', exact: true }).click()
    await page.getByRole('button', { name: en ? /Campaign/ : /Кампанія/ }).click()
    const choose = (id: string) => page.locator(`[data-mission-id="${id}"]`).getByRole('button').last().click()
    const launch = () => page.getByRole('button', { name: en ? 'Launch' : 'Запуск', exact: true }).click()
    const board = async () => {
      await page.getByRole('button', { name: en ? '← Main menu' : '← Головне меню', exact: true }).click()
      await page.getByRole('button', { name: en ? /Missions/ : /Місії/ }).click()
    }
    const buy = async (id: string) => {
      await page.getByTestId(`unlock-${id}`).focus()
      await page.keyboard.press('Enter')
    }
    await expect(page.locator('.upgrade-node')).toHaveCount(8)
    await expect(page.getByTestId('unlock-pl-relay')).toBeDisabled()
    await choose('wildfire')
    await launch()
    await expect(page.getByTestId('verdict')).toContainText(en ? /provisional/i : /попередн|умовн/i)
    await board()
    await expect(page.getByTestId('campaign-credits')).toContainText(/^120 /)
    await page.locator('.campaign-panel').screenshot({ path: `docs/screenshots/night03-tree-${locale}.png` })
    await buy('pl-visible-35')
    await choose('visible-mapping')
    await page.locator('.subsystem-tabs').getByRole('button', { name: en ? 'Payload' : 'Корисне навантаження', exact: true }).click()
    await page.locator('[data-part-id="pl-visible-35"]').click()
    await launch()
    await expect(page.getByTestId('verdict')).toContainText(en ? /provisional/i : /попередн|умовн/i)
    await board()
    await expect(page.getByTestId('campaign-credits')).toContainText(/^200 /)
    await expect(page.getByTestId('campaign-progress')).toContainText(/2.*4/)
    await page.getByTestId('refund-pl-visible-35').click()
    await board()
    await expect(page.getByTestId('campaign-credits')).toContainText(/^300 /)
    await buy('rf-x') // Fitting a compatible part opens the hangar.
    await expect(page.locator('[data-part-id="rf-x"]')).toHaveAttribute('aria-pressed', 'true')
    await board()
    await buy('pl-relay')
    await choose('packet-relay')
    await page.locator('.subsystem-tabs').getByRole('button', { name: en ? 'Ground service' : 'Наземний сервіс', exact: true }).click()
    await page.locator('[data-part-id="gs-network"]').click()
    await launch()
    await expect(page.getByTestId('verdict')).toContainText(en ? /provisional/i : /попередн|умовн/i)
    await board()
    await expect(page.getByTestId('campaign-credits')).toContainText(/^260 /)
    await choose('urban-heat')
    await page.locator('.subsystem-tabs').getByRole('button', { name: en ? 'Ground service' : 'Наземний сервіс', exact: true }).click()
    await page.locator('[data-part-id="gs-service"]').click()
    await launch()
    await expect(page.getByTestId('verdict')).toContainText(en ? /provisional/i : /попередн|умовн/i)
    await board()
    await expect(page.getByTestId('campaign-complete')).toBeVisible()
    await expect(page.getByTestId('campaign-credits')).toContainText(/^400 /)
    await buy('pl-visible-35')
    await expect(page.getByTestId('campaign-credits')).toContainText(/^300 /)
    const ledger = await page.evaluate(() => JSON.parse(localStorage.getItem('mission-forge.campaign.v1')!))
    expect(ledger.completedMissionIds).toEqual(['wildfire', 'visible-mapping', 'packet-relay', 'urban-heat'])
    expect(ledger.version).toBe(3)
    await expect(page.locator('.upgrade-node')).toHaveCount(8)
    const scan = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
    expect(scan.violations.map(v => v.id)).toEqual([])
    await page.locator('.campaign-panel').screenshot({ path: `docs/screenshots/night03-tree-complete-${locale}.png` })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.locator('.upgrade-branch').first().scrollIntoViewIfNeeded()
    await page.screenshot({ path: `docs/screenshots/night03-tree-phone-${locale}.png` })
    await page.setViewportSize({ width: 320, height: 844 })
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    await page.getByTestId('refund-pl-relay').focus()
    await page.keyboard.press('Enter')
    await expect(page.getByTestId('campaign-credits')).toContainText(/^440 /)
    await expect(page.getByTestId('campaign-complete')).toBeVisible()
    await page.getByTestId('unlock-pl-relay').focus()
    await page.keyboard.press('Enter')
    await expect(page.getByTestId('campaign-credits')).toContainText(/^300 /)
    const narrowScan = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
    expect(narrowScan.violations.map(v => v.id)).toEqual([])
    await page.getByTestId('upgrade-pl-relay').scrollIntoViewIfNeeded()
    await page.screenshot({ path: `docs/screenshots/night03-tree-reflow-${locale}.png` })
    await page.reload()
    if (!en) await page.getByRole('button', { name: 'Українська', exact: true }).click()
    await page.getByRole('button', { name: en ? /Campaign/ : /Кампанія/ }).click()
    await expect(page.getByTestId('campaign-complete')).toBeVisible()
    await expect(page.getByTestId('campaign-credits')).toContainText(/^300 /)
    expect(errors).toEqual([])
  })
}

test('tree refunds show historical basis and rebuy uses the current price, including after reload', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('mission-forge.academy.v1', 'seen'))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('./?renderer=svg')
  await page.evaluate(() => localStorage.setItem('mission-forge.campaign.v1', JSON.stringify({
    version: 2, completedMissionIds: ['wildfire', 'urban-heat', 'visible-mapping', 'packet-relay'],
    unlockedPartIds: ['rf-x', 'arr-deploy-xl', 'pl-visible-35', 'pl-relay'],
  })))
  await page.reload()
  await page.getByRole('button', { name: /Campaign/ }).click()
  await expect(page.getByTestId('campaign-complete')).toBeVisible()
  await expect(page.getByTestId('campaign-credits')).toContainText(/^0 /)
  await expect(page.locator('[data-mission-id="wildfire"] .mission-gallery-reward')).toContainText('100 credits')
  await expect(page.locator('[data-mission-id="wildfire"] .mission-gallery-reward')).toContainText('replay pays 0')
  await expect(page.getByTestId('refund-pl-relay')).toContainText('+100')
  await page.getByTestId('refund-pl-relay').click()
  await expect(page.getByTestId('campaign-credits')).toContainText(/^100 /)
  await expect(page.getByTestId('unlock-pl-relay')).toBeDisabled()
  await expect(page.getByTestId('upgrade-pl-relay')).toContainText('Need 40 more credits')
  await page.getByTestId('refund-arr-deploy-xl').click()
  // Neither refunded part was equipped; the tree stays open.
  await expect(page.getByTestId('campaign-credits')).toContainText(/^200 /)
  await page.getByTestId('unlock-pl-relay').click()
  await expect(page.getByTestId('campaign-credits')).toContainText(/^60 /)
  await expect(page.getByTestId('refund-pl-relay')).toContainText('+140')
  await page.reload()
  await page.getByRole('button', { name: /Campaign/ }).click()
  await expect(page.getByTestId('campaign-credits')).toContainText(/^60 /)
  await page.getByTestId('refund-pl-relay').click()
  await expect(page.getByTestId('campaign-credits')).toContainText(/^200 /)
})
