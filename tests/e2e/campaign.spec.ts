import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

for (const locale of ['en', 'ua'] as const) {
  test(`campaign earn → unlock → redesign survives reload without duplicate rewards (${locale})`, async ({ page }, testInfo) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('./')
    const useLanguage = async () => {
      if (locale === 'ua') await page.getByRole('button', { name: 'Українська', exact: true }).click()
    }
    await useLanguage()
    await page.getByRole('button', { name: locale === 'en' ? 'Play campaign' : 'Грати кампанію', exact: true }).click()
    await expect(page.locator('#mission-picker')).toBeFocused()
    await expect(page.locator('#mission-picker option[value="urban-heat"]')).toHaveCount(0)
    await expect(page.locator('#radioId option[value="rf-x"]')).toHaveCount(0)
    await expect(page.getByTestId('unlock-rf-x')).toBeDisabled()
    const run = () => page.getByRole('button', { name: locale === 'en' ? 'Run mission' : 'Запустити місію', exact: true })
    // Failed retries are free; the original engineering checks still enforce service.
    await page.locator('#groundId').selectOption('gs-network')
    await run().click()
    await expect(page.getByTestId('campaign-credits')).toContainText(/^0 /)
    await page.locator('#groundId').selectOption('gs-service')
    await run().click()
    await expect(page.getByTestId('verdict')).toContainText(locale === 'en' ? /provisional/i : /попередн|умовн/i)
    await expect(page.getByTestId('campaign-credits')).toContainText(/100/)
    await run().click()
    await expect(page.getByTestId('campaign-credits')).toContainText(/100/)
    await page.getByTestId('unlock-rf-x').focus()
    await page.keyboard.press('Enter')
    await expect(page.getByTestId('campaign-credits')).toContainText(/^0 /)
    await expect(page.getByTestId('unlock-rf-x')).toBeDisabled()
    await expect(page.locator('#radioId')).toBeFocused()
    await expect(page.locator('#radioId option[value="rf-x"]')).toHaveCount(1)
    await page.reload()
    // Reload starts direct play in English; the separate campaign save survives.
    await page.getByRole('button', { name: 'Play campaign', exact: true }).click()
    await expect(page.getByTestId('campaign-credits')).toContainText(/^0 /)
    await expect(page.getByTestId('unlock-rf-x')).toBeDisabled()
    await useLanguage()
    await page.locator('#mission-picker').focus()
    await page.keyboard.press('ArrowDown')
    await expect(page.locator('#mission-picker')).toHaveValue('urban-heat')
    await expect(page.locator('#mission-picker')).toBeFocused()
    await run().click()
    await expect(page.getByTestId('campaign-credits')).toContainText(/^0 /)
    await page.locator('#radioId').selectOption('rf-x')
    await page.locator('#groundId').selectOption('gs-single')
    await run().click()
    await expect(page.getByTestId('latency-value')).toContainText(/7[.,]1/)
    await expect(page.getByTestId('campaign-complete')).toHaveCount(0)
    await expect(page.getByTestId('campaign-credits')).toContainText(/100/)
    await expect(page.getByTestId('campaign-progress')).toContainText(/2.*4/)
    await run().click()
    await expect(page.getByTestId('campaign-credits')).toContainText(/100/)
    await page.getByTestId('unlock-pl-visible-35').click()
    await expect(page.getByTestId('campaign-credits')).toContainText(/^0 /)
    await page.getByTestId('contract-visible-mapping').click()
    await expect(page.locator('#mission-picker')).toHaveValue('visible-mapping')
    await run().click()
    await expect(page.getByTestId('campaign-credits')).toContainText(/^0 /)
    await page.getByTestId('fit-pl-visible-35').click()
    await expect(page.locator('#payloadId')).toBeFocused()
    await expect(page.locator('#payloadId')).toHaveValue('pl-visible-35')
    await expect(page.getByTestId('stale-notice')).toBeVisible()
    await run().click()
    await expect(page.getByTestId('campaign-credits')).toContainText(/100/)
    await expect(page.getByTestId('credit-delta')).toContainText(/\+100/)
    await page.getByTestId('unlock-pl-relay').click()
    await page.getByTestId('contract-packet-relay').click()
    await run().click()
    await expect(page.getByTestId('campaign-credits')).toContainText(/^0 /)
    await page.locator('.repair-cta').click()
    await expect(page.locator('#groundId')).toBeFocused()
    await page.locator('#groundId').selectOption('gs-network')
    await run().click()
    await expect(page.getByTestId('campaign-complete')).toBeVisible()
    await expect(page.getByTestId('campaign-progress')).toContainText(/4.*4/)
    await expect(page.getByTestId('campaign-credits')).toContainText(/100/)
    await run().click()
    await expect(page.getByTestId('campaign-credits')).toContainText(/100/)
    await expect(page.getByTestId('credit-delta')).toContainText(/^0 /)
    const scan = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
    expect(scan.violations.map(v => v.id)).toEqual([])
    await page.locator('#campaign-heading').focus()
    await page.locator('.campaign-panel').screenshot({ path: testInfo.outputPath(`campaign-complete-${locale}.png`) })
    await page.setViewportSize({ width: 320, height: 844 })
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
    expect(await page.evaluate(() => [...document.querySelectorAll('body *')].filter(el => el.getBoundingClientRect().right > innerWidth + 1).map(el => el.tagName).slice(0, 10))).toEqual([])
    const mobileScan = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
    expect(mobileScan.violations.map(v => v.id)).toEqual([])
    expect(await page.evaluate(() => document.getAnimations().length)).toBe(0)
    await page.reload()
    await page.getByRole('button', { name: 'Play campaign', exact: true }).click()
    await expect(page.getByTestId('campaign-complete')).toBeVisible()
    await expect(page.getByTestId('campaign-credits')).toContainText(/100/)
    await page.getByRole('button', { name: 'Run mission', exact: true }).click()
    await expect(page.getByTestId('campaign-credits')).toContainText(/100/)
    await page.getByRole('button', { name: 'Return to direct play', exact: true }).click()
    await expect(page.locator('#mission-picker option[value="urban-heat"]')).toHaveCount(1)
    await expect(page.locator('#radioId option[value="rf-x"]')).toHaveCount(1)
    expect(errors).toEqual([])
  })
}

test('array-first route, reversible upgrades and old-save migration preserve credits and unrelated storage', async ({ page }) => {
  await page.goto('./')
  await page.evaluate(() => {
    localStorage.setItem('unrelated.user.setting', 'keep-me')
    localStorage.setItem('mission-forge.campaign.v1', JSON.stringify({ version: 1, completedMissionIds: ['wildfire', 'urban-heat'], unlockedPartIds: ['arr-deploy-xl'] }))
  })
  await page.reload()
  await page.getByRole('button', { name: 'Play campaign', exact: true }).click()
  await expect(page.getByTestId('campaign-credits')).toContainText(/100/)
  await expect(page.getByTestId('campaign-progress')).toContainText(/2.*4/)
  await page.getByTestId('fit-arr-deploy-xl').click()
  await expect(page.locator('#arrayId')).toBeFocused()
  await expect(page.locator('#arrayId')).toHaveValue('arr-deploy-xl')
  await page.locator('#mission-picker').selectOption('urban-heat')
  await page.locator('#arrayId').selectOption('arr-deploy-xl')
  await page.locator('#batteryId').selectOption('bat-m')
  await page.locator('#groundId').selectOption('gs-service')
  await page.getByRole('button', { name: 'Run mission', exact: true }).click()
  await expect(page.getByTestId('verdict')).toContainText(/provisional/i)
  await expect(page.getByTestId('campaign-credits')).toContainText(/100/)
  await page.getByTestId('refund-arr-deploy-xl').click()
  await expect(page.getByTestId('campaign-credits')).toContainText(/200/)
  await expect(page.locator('#arrayId')).toBeFocused()
  await expect(page.getByTestId('stale-notice')).toBeVisible()
  await page.getByTestId('unlock-rf-x').click()
  await page.getByTestId('unlock-pl-visible-35').click()
  await page.getByTestId('contract-visible-mapping').click()
  await page.getByTestId('fit-pl-visible-35').click()
  await page.getByRole('button', { name: 'Run mission', exact: true }).click()
  await expect(page.getByTestId('campaign-credits')).toContainText(/100/)
  await page.getByTestId('unlock-pl-relay').click()
  await page.getByTestId('contract-packet-relay').click()
  await page.locator('#groundId').selectOption('gs-network')
  await page.getByRole('button', { name: 'Run mission', exact: true }).click()
  await expect(page.getByTestId('campaign-complete')).toBeVisible()
  const state = await page.evaluate(() => ({
    campaign: JSON.parse(localStorage.getItem('mission-forge.campaign.v1')!),
    unrelated: localStorage.getItem('unrelated.user.setting'),
  }))
  expect(state.campaign.version).toBe(2)
  expect(state.campaign.completedMissionIds).toEqual(['wildfire', 'urban-heat', 'visible-mapping', 'packet-relay'])
  expect(state.unrelated).toBe('keep-me')
})
