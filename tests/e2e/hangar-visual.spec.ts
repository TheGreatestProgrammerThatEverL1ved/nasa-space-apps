import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test.use({ deviceScaleFactor: 1 })

for (const [label, width, height] of [['desktop', 1440, 960], ['phone', 390, 844]] as const) {
  test(`locked hangar capture ${label}`, async ({ page }) => {
    await page.setViewportSize({ width, height })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.addInitScript(() => localStorage.setItem('mission-forge.academy.v1', 'seen'))
    await page.goto('./')
    await expect(page.locator('.craft-scene')).toHaveAttribute('data-renderer', 'webgl')
    await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); window.scrollTo(0, 0) })
    await page.screenshot({ path: `docs/screenshots/hangar04-title-${label}-en.png`, fullPage: label === 'phone' })
    await page.getByRole('button', { name: /Customize/ }).click()
    await page.locator('[data-part-id="arr-deploy-xl"]').click()
    await page.getByRole('button', { name: 'Reset camera', exact: true }).click()
    await expect(page.locator('.craft-scene')).toHaveAttribute('data-renderer', 'webgl')
    await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); window.scrollTo(0, 0) })
    await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
    await page.screenshot({ path: `docs/screenshots/hangar04-${process.env.HANGAR_CAPTURE ?? 'after'}-${label}-en.png`, fullPage: label === 'phone' })
  })
}

for (const locale of ['en', 'ua'] as const) {
  test(`compact hangar direct equipping, disclosures and flight path (${locale})`, async ({ page }) => {
    const en = locale === 'en'
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.setViewportSize({ width: 1440, height: 960 })
    await page.addInitScript(() => localStorage.setItem('mission-forge.academy.v1', 'seen'))
    await page.goto('./')
    if (!en) await page.getByRole('button', { name: 'Українська', exact: true }).click()
    await page.getByRole('button', { name: en ? /Customize/ : /Налаштувати/ }).focus()
    await page.keyboard.press('Enter')
    await expect(page.locator('#hangar-title')).toBeFocused()
    await expect(page.locator('.viewport-slots')).toHaveCount(0)
    const scene = page.locator('.craft-scene')
    await expect(scene).toHaveAttribute('data-renderer', 'webgl')
    await expect(scene).toHaveAttribute('data-motion', 'off')
    const stage = page.locator('.craft-inspection')
    const frame = async () => {
      await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
      return stage.screenshot()
    }
    const wingBefore = await frame()
    await page.screenshot({ path: `docs/screenshots/hangar04-wing-before-${locale}.png` })
    await page.locator('[data-part-id="arr-deploy-xl"]').focus()
    await page.keyboard.press('Enter')
    await expect(page.locator('[data-part-id="arr-deploy-xl"]')).toBeFocused()
    await expect(scene).toHaveAttribute('data-array-id', 'arr-deploy-xl')
    expect(wingBefore.equals(await frame())).toBe(false)
    await expect(page.locator('.part-hud')).toContainText(en ? '135 W' : '135 Вт')
    await page.screenshot({ path: `docs/screenshots/hangar04-wing-${locale}.png` })
    const slots = page.getByRole('navigation', { name: en ? 'Subsystems and mission choices' : 'Підсистеми та параметри місії' })
    await expect(slots).toHaveCount(1)
    await expect(slots.getByRole('button')).toHaveCount(8)
    await slots.getByRole('button', { name: en ? 'Radio package' : 'Радіопакет', exact: true }).click()
    const antennaBefore = await frame()
    await page.screenshot({ path: `docs/screenshots/hangar04-antenna-before-${locale}.png` })
    await page.locator('[data-part-id="rf-uhf"]').click()
    await expect(scene).toHaveAttribute('data-radio-id', 'rf-uhf')
    expect(await page.locator('.part-hud').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
    expect(antennaBefore.equals(await frame())).toBe(false)
    await page.screenshot({ path: `docs/screenshots/hangar04-antenna-${locale}.png` })
    // Restore a viable wing/radio and repair cadence without changing physics.
    await page.locator('[data-part-id="rf-x"]').click()
    await slots.getByRole('button', { name: en ? 'Solar array' : 'Сонячна батарея', exact: true }).click()
    await page.locator('[data-part-id="arr-deploy-l"]').click()
    await slots.getByRole('button', { name: en ? 'Ground service' : 'Наземний сервіс', exact: true }).click()
    await page.locator('[data-part-id="gs-network"]').click()
    await page.getByRole('button', { name: en ? 'Launch' : 'Запуск', exact: true }).click()
    await expect(page.getByTestId('verdict')).toBeFocused()
    await expect(page.getByTestId('verdict')).toContainText(en ? /provisional/i : /попередн|умовн/i)
    await page.screenshot({ path: `docs/screenshots/hangar04-debrief-${locale}.png` })
    expect(await page.evaluate(() => localStorage.getItem('mission-forge.campaign.v1'))).toBeNull()
    const scan = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(scan.violations.map(v => v.id)).toEqual([])
    expect(errors).toEqual([])
  })
}

test('hangar fallback remains dynamic with one navigation and narrow bilingual reflow', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('mission-forge.academy.v1', 'seen'))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('./?renderer=svg')
  await page.getByRole('button', { name: 'Українська', exact: true }).click()
  await page.getByRole('button', { name: /Налаштувати/ }).click()
  const scene = page.locator('.craft-scene')
  await expect(scene).toHaveAttribute('data-renderer', 'svg')
  await page.locator('[data-part-id="arr-body"]').click()
  const body = await page.locator('.craft-fallback svg').screenshot()
  await page.locator('[data-part-id="arr-deploy-xl"]').click()
  expect(body.equals(await page.locator('.craft-fallback svg').screenshot())).toBe(false)
  await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); window.scrollTo(0, 0) })
  await page.screenshot({ path: 'docs/screenshots/hangar04-fallback-phone-ua.png', fullPage: true })
  const slots = page.getByRole('navigation', { name: 'Підсистеми та параметри місії' })
  await slots.getByRole('button', { name: 'Радіопакет', exact: true }).click()
  await page.locator('[data-part-id="rf-uhf"]').click()
  const whip = await page.locator('.craft-fallback svg').screenshot()
  await page.locator('[data-part-id="rf-x"]').click()
  expect(whip.equals(await page.locator('.craft-fallback svg').screenshot())).toBe(false)
  await expect(page.locator('.part-hud details').first()).not.toHaveAttribute('open', '')
  await page.locator('.part-hud details > summary').first().click()
  await expect(page.locator('.part-hud details').first()).toHaveAttribute('open', '')
  await page.locator('.part-hud details > summary').first().click()
  await page.setViewportSize({ width: 320, height: 844 })
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
  for (const button of await slots.getByRole('button').all()) {
    await button.click()
    const overflow = await page.evaluate(() => [...document.querySelectorAll('body *')].filter(el => {
      const rect = el.getBoundingClientRect()
      // The SVG cutaway intentionally clips distant wings at its viewBox.
      // Check page layout, not off-view geometry inside the clipped drawing.
      return el instanceof HTMLElement && rect.width > 0 && rect.right > innerWidth + 1
    }).filter(el => !el.closest('.sr-only')).map(el => ({ tag: el.tagName, cls: el.getAttribute('class'), text: el.textContent?.slice(0, 80), parent: el.parentElement?.className, right: el.getBoundingClientRect().right })).slice(0, 15))
    expect(overflow).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  }
  const scan = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(scan.violations.map(v => v.id)).toEqual([])
  await page.screenshot({ path: 'docs/screenshots/hangar04-fallback-reflow-ua.png', fullPage: true })
})

