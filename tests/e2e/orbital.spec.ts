import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('orbital slice renders real WebGL and swaps shared hardware with stationary inspection', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.goto('./')
  await expect(page.getByRole('heading', { name: /MISSION FORGE/ })).toBeVisible()
  await expect(page.locator('.craft-scene')).toHaveAttribute('data-renderer', 'webgl')
  await expect(page.locator('.craft-scene')).toHaveAttribute('data-motion', 'off')
  await expect(page.locator('.craft-scene canvas')).toBeVisible()
  await expect(page.locator('.craft-fallback')).toHaveCount(0)
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
  await page.screenshot({ path: 'docs/screenshots/night03-menu-en.png' })
  await page.getByRole('button', { name: /Customize/ }).click()
  const scene = page.locator('.craft-scene')
  await expect(scene).toHaveAttribute('data-array-id', 'arr-deploy-l')
  await page.locator('.camera-controls').getByRole('button', { name: 'Reset camera' }).click()
  await page.screenshot({ path: 'docs/screenshots/night03-hangar-before-en.png' })
  await page.locator('.craft-inspection').screenshot({ path: 'docs/screenshots/night03-craft-before-en.png' })
  await page.locator('[data-part-id="arr-deploy-xl"]').click()
  await expect(scene).toHaveAttribute('data-array-id', 'arr-deploy-xl')
  await expect(page.locator('.part-hud')).toContainText('135 W')
  await page.screenshot({ path: 'docs/screenshots/night03-hangar-after-en.png' })
  await page.locator('.craft-inspection').screenshot({ path: 'docs/screenshots/night03-craft-after-en.png' })
  await page.getByRole('button', { name: '← Main menu' }).click()
  await expect(page.locator('.craft-scene')).toHaveAttribute('data-array-id', 'arr-deploy-xl')
  await expect(page.locator('.craft-scene')).toHaveAttribute('data-renderer', 'webgl')
  await expect(page.locator('.craft-fallback')).toHaveCount(0)
  await page.screenshot({ path: 'docs/screenshots/night03-menu-equipped-en.png' })
  await page.getByRole('button', { name: /Customize/ }).click()
  await expect(scene).toHaveAttribute('data-renderer', 'webgl')
  await expect(page.locator('.craft-fallback')).toHaveCount(0)
  const slots = page.getByRole('navigation', { name: 'Subsystems and mission choices' })
  await slots.getByRole('button', { name: 'Radio package', exact: true }).click()
  await page.locator('[data-part-id="rf-uhf"]').click()
  await expect(scene).toHaveAttribute('data-radio-id', 'rf-uhf')
  await page.screenshot({ path: 'docs/screenshots/night03-antenna-en.png' })
  await slots.getByRole('button', { name: 'Battery', exact: true }).click()
  await page.locator('[data-part-id="bat-l"]').click()
  await expect(scene).toHaveAttribute('data-battery-id', 'bat-l')
  await expect(page.locator('.inspection-label')).toContainText('INTERNAL CUTAWAY')
  await page.screenshot({ path: 'docs/screenshots/night03-battery-en.png' })
  const scan = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(scan.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) }))).toEqual([])
  expect(errors).toEqual([])
})

test('SVG fallback equips, preserves language and supports phone/reflow and launch', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('./?renderer=svg')
  await page.getByRole('button', { name: 'Українська', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'uk')
  await expect(page.locator('.craft-scene')).toHaveAttribute('data-renderer', 'svg')
  await page.screenshot({ path: 'docs/screenshots/night03-menu-mobile-uk.png', fullPage: true })
  await page.getByRole('button', { name: /Налаштувати/ }).click()
  await page.locator('[data-part-id="arr-body"]').click()
  await expect(page.locator('.craft-scene')).toHaveAttribute('data-array-id', 'arr-body')
  const beforeRotation = await page.locator('.craft-fallback svg').screenshot()
  await page.getByRole('button', { name: 'Обернути праворуч' }).click()
  const afterRotation = await page.locator('.craft-fallback svg').screenshot()
  expect(beforeRotation.equals(afterRotation)).toBe(false)
  await page.getByRole('button', { name: 'Скинути камеру' }).click()
  await page.screenshot({ path: 'docs/screenshots/night03-hangar-mobile-uk.png', fullPage: true })
  await page.getByRole('button', { name: '← Головне меню' }).click()
  await expect(page.locator('.craft-scene')).toHaveAttribute('data-array-id', 'arr-body')
  await page.getByRole('button', { name: /Налаштувати/ }).click()
  await page.setViewportSize({ width: 320, height: 844 })
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  expect(await page.evaluate(() => [...document.querySelectorAll('body *')].filter(el => {
    const r = el.getBoundingClientRect()
    return el instanceof HTMLElement && r.width > 0 && r.right > innerWidth + 1
  }).map(el => ({ tag: el.tagName, cls: el.className, right: el.getBoundingClientRect().right })).slice(0, 15))).toEqual([])
  await page.screenshot({ path: 'docs/screenshots/night03-hangar-reflow-uk.png', fullPage: true })
  await page.getByRole('button', { name: 'Запуск', exact: true }).click()
  await expect(page.getByTestId('verdict')).toContainText('Місія потребує виправлення')
  expect(errors).toEqual([])
})

test('actual context loss replaces the canvas without losing draft controls', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('./')
  await expect(page.locator('.craft-scene')).toHaveAttribute('data-renderer', 'webgl')
  await expect(page.locator('.craft-scene canvas')).toBeVisible()
  await expect(page.locator('.craft-fallback')).toHaveCount(0)
  const lost = await page.locator('.craft-scene canvas').evaluate((node: HTMLCanvasElement) => {
    const gl = node.getContext('webgl2') ?? node.getContext('webgl')
    const extension = gl?.getExtension('WEBGL_lose_context')
    extension?.loseContext()
    return !!extension
  })
  expect(lost).toBe(true)
  await expect(page.locator('.craft-scene')).toHaveAttribute('data-renderer', 'svg')
  await expect(page.locator('.craft-fallback')).toBeVisible()
  await page.getByRole('button', { name: /Customize/ }).click()
  await page.locator('[data-part-id="arr-deploy-xl"]').click()
  await expect(page.locator('.craft-scene')).toHaveAttribute('data-array-id', 'arr-deploy-xl')
  expect(errors).toEqual([])
})

test('unavailable WebGL uses working fallback from first paint', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(window, 'WebGLRenderingContext', { value: undefined })
    Object.defineProperty(window, 'WebGL2RenderingContext', { value: undefined })
  })
  await page.goto('./')
  await expect(page.locator('.craft-scene')).toHaveAttribute('data-renderer', 'svg')
  await expect(page.locator('canvas')).toHaveCount(0)
  await page.getByRole('button', { name: /Customize/ }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Spacecraft hangar' })).toBeFocused()
  await page.locator('[data-part-id="arr-body"]').focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('[data-part-id="arr-body"]')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.craft-scene')).toHaveAttribute('data-array-id', 'arr-body')
})

