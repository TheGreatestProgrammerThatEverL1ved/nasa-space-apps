import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { assembleHangar, FIRST_PLAYER, STARTER_PASS } from './assembly'

for(const locale of ['en','ua'] as const)for(const [viewport,width,text] of [['desktop',1440,100],['phone',390,100],['reflow',320,200]] as const){
  test(`QA density, empty assembly, repair and research ${locale} ${viewport}`,async({page},testInfo)=>{
    test.setTimeout(90000)
    const en=locale==='en',errors:string[]=[]
    page.on('pageerror',e=>errors.push(e.message))
    await page.addInitScript(()=>localStorage.setItem('mission-forge.academy.v1','seen'))
    await page.emulateMedia({reducedMotion:'reduce'})
    await page.setViewportSize({width,height:960})
    await page.goto(viewport==='desktop'?'./':'./?renderer=svg')
    if(text===200)await page.evaluate(()=>{document.documentElement.style.fontSize='200%'})
    if(!en)await page.getByRole('button',{name:'Українська',exact:true}).click()
    const counts:Record<string,number>={}
    const capture=async(screen:string)=>{
      if(viewport==='desktop' && await page.locator('.craft-scene').count()){
        await expect(page.locator('.craft-scene')).toHaveAttribute('data-renderer','webgl')
        await expect(page.locator('.craft-fallback')).toHaveCount(0)
      }
      counts[screen]=await page.locator('p').evaluateAll(nodes=>nodes.filter(p=>
        (p as HTMLElement).checkVisibility() && !p.closest('.sr-only') && !p.classList.contains('sr-only')
        && !p.closest('details:not([open])')).length)
      expect(counts[screen],`${screen} default paragraph limit`).toBeLessThanOrEqual(
        screen==='missions'?4:screen==='debrief-failure'?3:screen==='debrief'?2:1)
      expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
      await page.screenshot({path:`docs/screenshots/qa/after-${screen}-${viewport}-${locale}.png`,fullPage:true})
    }
    const menu=()=>page.getByRole('button',{name:en?'← Main menu':'← Головне меню',exact:true}).click()
    const customize=()=>page.getByRole('button',{name:en?'Customize':'Налаштувати',exact:true}).click()
    const launch=()=>page.getByRole('button',{name:en?'Launch':'Запуск',exact:true}).click()
    await expect(page.locator('.menu-actions button')).toHaveCount(5)
    await capture('menu')
    await customize()
    await expect(page.getByTestId('build-progress')).toHaveText('0/8')
    await expect(page.getByRole('button',{name:en?'Launch':'Запуск',exact:true})).toBeDisabled()
    for(const field of ['bus','payload','array','battery','radio'])await expect(page.locator('.craft-scene')).toHaveAttribute(`data-${field}-id`,'')
    await capture('hangar-empty')
    await assembleHangar(page)
    await expect(page.getByTestId('build-progress')).toHaveText('8/8')
    await expect(page.locator('.subsystem-tabs button')).toHaveCount(8)
    expect(await page.locator('.part-hud > .hud-stats > div').count()).toBeLessThanOrEqual(3)
    await capture('hangar')
    await launch()
    await expect(page.getByTestId('verdict')).toContainText(en?/repair|failure/i:/виправ|невда|не відповідає/i)
    await expect(page.getByTestId('important-number')).toContainText(/7[.,]1/)
    await expect(page.locator('.compact-debrief > button')).toHaveCount(1)
    await expect(page.locator('.full-report')).not.toHaveAttribute('open','')
    await capture('debrief-failure')
    await page.getByTestId('compact-debrief').getByRole('button').click()
    await page.locator('[data-slot="groundId"]').click()
    await page.locator('[data-part-id="gs-network"]').click()
    await launch()
    await expect(page.getByTestId('verdict')).toContainText(en?/provisional/i:/попередн|умовн/i)
    await capture('debrief')
    await menu()
    await page.getByRole('button',{name:en?'Missions':'Місії',exact:true}).click()
    for(const card of await page.locator('.mission-card').all()){
      await expect(card.locator('.mission-gallery-objective')).toHaveCount(1)
      expect(await card.locator('.goal-chips > span').count()).toBeLessThanOrEqual(3)
      await expect(card.getByRole('button')).toHaveCount(1)
    }
    await capture('missions')
    await menu()
    await page.getByRole('button',{name:en?'Research':'Дослідження',exact:true}).click()
    await expect(page.locator('[data-research-id]')).toHaveCount(12)
    await expect(page.locator('.game-brand')).toContainText(en?'SANDBOX':'ПІСОЧНИЦЯ')
    await page.getByRole('button',{name:en?'Enter Campaign':'Перейти до кампанії',exact:true}).click()
    await expect(page.getByTestId('research-wallet')).toHaveText(en?'0 credits':'0 кредитів')
    await page.getByRole('button',{name:en?'Back':'Назад',exact:true}).click()
    await customize()
    await expect(page.getByTestId('build-progress')).toHaveText('0/8')
    await assembleHangar(page,STARTER_PASS)
    await launch()
    await expect(page.getByTestId('verdict')).toContainText(en?/provisional/i:/попередн|умовн/i)
    await page.getByRole('button',{name:en?'Research':'Дослідження',exact:true}).click()
    const node=page.locator('[data-research-id="rf-x"]')
    await expect(node).toHaveAttribute('data-state','buyable')
    await node.focus()
    await expect(node).toHaveCSS('border-top-color','rgb(245, 214, 96)')
    await expect(page.locator('[data-research-id="bus-12u"]')).toHaveCSS('border-top-color','rgb(132, 218, 178)')
    await expect(page.locator('[data-research-id="pl-relay"]')).toHaveCSS('border-top-color','rgb(241, 142, 142)')
    await expect(page.getByTestId('research-price')).toContainText('100')
    await capture('research')
    await page.keyboard.press('Enter')
    await expect(node).toHaveAttribute('data-state','owned')
    await expect(node).toHaveCSS('border-top-color','rgb(132, 218, 178)')
    await expect(page.getByTestId('research-wallet')).toHaveText(en?'20 credits':'20 кредитів')
    await page.keyboard.press('Enter')
    await expect(page.getByTestId('research-wallet')).toHaveText(en?'20 credits':'20 кредитів')
    await menu();await customize()
    await page.locator('[data-slot="radioId"]').click()
    await expect(page.locator('[data-part-id="rf-s"]')).toHaveAttribute('aria-pressed','true')
    await expect(page.locator('[data-part-id="rf-x"]')).toHaveAttribute('aria-pressed','false')
    const scan=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
    expect(scan.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))).toEqual([])
    expect(errors).toEqual([])
    await testInfo.attach('density-counts',{body:JSON.stringify({locale,viewport,width,text,counts}),contentType:'application/json'})
    console.info('QA_COUNTS',JSON.stringify({locale,viewport,width,text,counts}))
    // Keep source imports exercised: no launch helper supplies missing selections.
    expect(FIRST_PLAYER.launcherId).toBe('lv-heavy')
  })
}

test('touch Research first previews a visible price, then purchases exactly once',async({browser,baseURL})=>{
  const context=await browser.newContext({baseURL,hasTouch:true,isMobile:true,viewport:{width:390,height:844}})
  const page=await context.newPage()
  await page.addInitScript(()=>localStorage.setItem('mission-forge.academy.v1','seen'))
  await page.goto('./?renderer=svg')
  await page.evaluate(()=>localStorage.setItem('mission-forge.campaign.v1',JSON.stringify({version:1,completedMissionIds:['wildfire'],unlockedPartIds:[]})))
  await page.reload()
  await page.getByRole('button',{name:'Campaign',exact:true}).tap()
  await page.getByRole('button',{name:'Research',exact:true}).tap()
  const node=page.locator('[data-research-id="rf-x"]')
  await node.tap()
  await expect(page.getByTestId('research-price')).toBeInViewport()
  await expect(page.getByTestId('research-price')).toHaveText('100 credits')
  await expect(page.getByTestId('research-wallet')).toHaveText('100 credits')
  await node.tap()
  await expect(page.getByTestId('research-wallet')).toHaveText('0 credits')
  await node.tap()
  await expect(page.getByTestId('research-wallet')).toHaveText('0 credits')
  await context.close()
})
