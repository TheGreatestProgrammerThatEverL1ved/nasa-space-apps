import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

for (const locale of ['en', 'ua'] as const) {
  test(`urban mission: volume repair, cheaper station and honest latency (${locale})`, async ({ page }, testInfo) => {
    const errors: string[] = []
    const failedAssets: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('response', response => { if (response.status() >= 400) failedAssets.push(response.url()) })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('./?view=engineering')
    if (locale === 'ua') await page.getByRole('button', { name: 'Українська', exact: true }).click()
    const picker = page.locator('#mission-picker')
    await picker.focus()
    await page.keyboard.press('ArrowDown')
    await expect(picker).toHaveValue('urban-heat')
    await expect(picker).toBeFocused()
    await expect(page.locator('html')).toHaveAttribute('lang', locale === 'en' ? 'en' : 'uk')
    await expect(page.getByTestId('latency-value')).toHaveCount(0)
    const run = page.getByRole('button', { name: locale === 'en' ? 'Run mission' : 'Запустити місію', exact: true })
    await run.click()
    await expect(page.getByTestId('verdict')).toBeFocused()
    await expect(page.getByTestId('verdict')).toContainText(locale === 'en' ? /repair/i : /ремонт|виправ|невда|не відповідає/i)
    await expect(page.getByTestId('latency-value')).toContainText(locale === 'en' ? /unavailable/i : /недоступ|немає/i)
    const details = page.locator('details.drawer').first()
    await details.locator(':scope > summary').click()
    await expect(page.getByTestId('requirement-UH-DELIVERY')).toContainText(locale === 'en' ? /upper bound/i : /верхня межа/i)
    await expect(page.getByTestId('requirement-UH-DELIVERY')).toContainText(/1[.,]134/)
    await page.locator('.repair-cta').click()
    await expect(page.locator('#radioId')).toBeFocused()
    await page.locator('#radioId').selectOption('rf-x')
    await expect(page.getByTestId('stale-notice')).toBeVisible()
    await run.click()
    await expect(page.getByTestId('verdict')).toContainText(locale === 'en' ? /provisional/i : /попередн|умовн/i)
    await page.locator('#groundId').selectOption('gs-single')
    await run.click()
    await expect(page.getByTestId('latency-value')).toContainText(/7[.,]1/)
    await expect(page.getByTestId('requirement-UH-LATENCY')).toContainText(/12/)
    await expect(page.getByTestId('report-origin')).toContainText(/evaluator|обчислювач/i)
    const scan = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
    expect(scan.violations.map(v => v.id)).toEqual([])
    await page.screenshot({ path: testInfo.outputPath(`urban-pass-${locale}.png`) })
    await page.setViewportSize({ width: 320, height: 844 })
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
    for (const summary of await page.locator('main details > summary').all()) {
      if (!(await summary.evaluate(el => el.parentElement?.hasAttribute('open')))) await summary.click()
    }
    const overflow = await page.evaluate(() => [...document.querySelectorAll('body *')]
      .filter(el => el.getBoundingClientRect().right > innerWidth + 1)
      .map(el => el.tagName).slice(0, 10))
    expect(overflow).toEqual([])
    expect(await page.locator('.skip-link').evaluate(el => el.getBoundingClientRect().bottom)).toBeLessThanOrEqual(0)
    const expandedScan = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
    expect(expandedScan.violations.map(v => v.id)).toEqual([])
    expect(await page.evaluate(() => document.getAnimations().length)).toBe(0)
    await page.screenshot({ path: testInfo.outputPath(`urban-mobile-${locale}.png`) })
    await picker.focus()
    await page.keyboard.press('ArrowUp')
    await expect(picker).toHaveValue('wildfire')
    await expect(picker).toBeFocused()
    await expect(page.getByTestId('latency-value')).toHaveCount(0)
    await run.click()
    await expect(page.getByTestId('latency-value')).toContainText(/7[.,]1/)
    await expect(page.getByTestId('verdict')).toContainText(locale === 'en' ? /repair/i : /ремонт|виправ|невда|не відповідає/i)
    expect(errors).toEqual([])
    expect(failedAssets).toEqual([])
  })
}
